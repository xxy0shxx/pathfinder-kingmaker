/**
 * Поиск фокусов по названию или традиции
 */
export function searchCantrips(query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return PF2E_CANTRIPS;
    return PF2E_CANTRIPS.filter(c =>
        c.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        c.traditions.some(t => t.toLowerCase().includes(q))
    );
}
