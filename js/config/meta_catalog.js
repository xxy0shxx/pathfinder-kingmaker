export function searchMetaCatalog(list, query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return list;
    return list.filter(x => x.name.toLowerCase().replace(/ё/g, 'е').includes(q));
}
