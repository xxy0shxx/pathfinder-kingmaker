// Экспортируемая вспомогательная функция поиска по каталогу происхождений
export function searchBackgroundsCatalog(query) {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return [];
    return PF2E_BACKGROUNDS.filter(b =>
        b.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        b.skillName.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        b.feat.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        b.source.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}