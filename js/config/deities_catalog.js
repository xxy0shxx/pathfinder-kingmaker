export function searchDeitiesCatalog(query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return PF2E_DEITIES;
    return PF2E_DEITIES.filter(d =>
        d.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        d.title.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        d.weapon.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        d.domains.some(dom => dom.toLowerCase().replace(/ё/g, 'е').includes(q))
    );
}