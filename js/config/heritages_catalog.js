// Экспортируемая вспомогательная функция поиска по родословным
export function searchHeritagesCatalog(query, ancestryFilter = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');

    let list = PF2E_HERITAGES;
    if (ancestryFilter) {
        list = list.filter(h => h.ancestry === ancestryFilter);
    }

    if (!q) return list;
    return list.filter(h => h.name.toLowerCase().replace(/ё/g, 'е').includes(q));
}
