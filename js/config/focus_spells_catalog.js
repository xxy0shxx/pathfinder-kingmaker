export function searchFocusSpells(query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return PF2E_FOCUS_SPELLS;
    return PF2E_FOCUS_SPELLS.filter(f =>
        f.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        f.source.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        f.notes.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}
