// Вспомогательная функция поиска по чертам навыков
export function searchSkillFeats(query) {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return [];
    return PF2E_SKILL_FEATS.filter(f => f.name.toLowerCase().replace(/ё/g, 'е').includes(q));
}
