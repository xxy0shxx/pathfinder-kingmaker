export function searchSpellsLvl7(query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return PF2E_SPELLS_LVL7;
    return PF2E_SPELLS_LVL7.filter(s =>
        s.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        s.traditions.some(t => t.toLowerCase().includes(q)) ||
        s.notes.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}
