export function searchRitualsCatalog(query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return PF2E_RITUALS;
    return PF2E_RITUALS.filter(r =>
        r.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        r.primaryCheck.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        r.desc.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}
