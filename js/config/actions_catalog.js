export function searchActionsCatalog(query = '', categoryFilter = 'all') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    let list = PF2E_ACTIONS_CATALOG;
    if (categoryFilter && categoryFilter !== 'all') {
        list = list.filter(a => a.category === categoryFilter);
    }
    if (!q) return list;
    return list.filter(a =>
        a.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        a.traits.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        (a.className && a.className.toLowerCase().replace(/ё/g, 'е').includes(q)) ||
        a.desc.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}

