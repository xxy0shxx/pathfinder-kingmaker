// Вспомогательная функция поиска по общим чертам
export function searchGeneralFeats(query) {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return [];
    return PF2E_GENERAL_FEATS.filter(f =>
        f.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        f.desc.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}