export function searchItemsCatalog(query = '') {
    const q = String(query || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!q) return PF2E_ITEMS_CATALOG;
    return PF2E_ITEMS_CATALOG.filter(it =>
        it.name.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        it.category.toLowerCase().replace(/ё/g, 'е').includes(q) ||
        it.notes.toLowerCase().replace(/ё/g, 'е').includes(q)
    );
}

/**
 * Проверяет, является ли предмет боевым расходником (зелья, эликсиры, бомбы, свитки и т.д.)
 */
export function isCombatConsumable(itemName, itemNotes = '') {
    const cleanName = String(itemName || '').trim().toLowerCase().replace(/ё/g, 'е');
    if (!cleanName) return false;

    // Поддержка проверки как с иконками, так и без них
    const found = PF2E_ITEMS_CATALOG.find(it => {
        const targetName = it.name.toLowerCase().replace(/ё/g, 'е');
        return targetName === cleanName || targetName.slice(3) === cleanName;
    });

    if (found) {
        return /^(Зелье|Эликсир|Бомба|Свиток|Талисман|Масло)/i.test(found.category);
    }

    // Если предмет вписан игроком вручную — проверяем по ключевым словам
    const text = `${cleanName} ${String(itemNotes || '').toLowerCase().replace(/ё/g, 'е')}`;
    return /(зель|эликсир|бомб|склянк|свиток|масл|талисман|противояд|античум)/i.test(text);
}

/**
 * Подсчитывает общую массу (Bulk) снаряжения и монет персонажа по правилам Pathfinder 2e
 * (10 Л = 1 Масса; 1000 монет = 1 Масса; лимит без перегрузки = 5 + СИЛ; максимум = 10 + СИЛ)
 */

export function calculateCharacterBulk(stats) {
    const strMod = Number(stats?.str) || 0;
    let extraLimit = 0;
    let lightCount = 0;
    let heavyBulk = 0;

    // 1. Точный словарь масс для всех предметов из items_catalog.js (в десятых долях: 1 = 1 Л, 10 = 1 Масса)
    const knownBulkTenths = [
        { keys: ['набор искателя приключений', 'adventurer'], tenths: 10 },
        { keys: ['сух. паек', 'сухой паек', 'рацион', 'rations'], tenths: 1 },
        { keys: ['веревка', 'верёвка', 'rope'], tenths: 10 },
        { keys: ['крюк-кошка', 'grappling'], tenths: 1 },
        { keys: ['факел', 'torch'], tenths: 1 },
        { keys: ['направленный фонарь', 'фонарь', 'lantern'], tenths: 1 },
        { keys: ['спальник', 'bedroll'], tenths: 1 },
        { keys: ['ломик', 'crowbar'], tenths: 1 },
        { keys: ['набор лекаря', 'healer'], tenths: 10 },
        { keys: ['воровские инструменты', 'thieves'], tenths: 1 },
        { keys: ['ремонтный набор', 'repair'], tenths: 10 },
        { keys: ['набор алхимика', 'alchemist'], tenths: 20 },
        { keys: ['набор скалолаза', 'climbing'], tenths: 10 },
        { keys: ['набор для маскировки', 'disguise'], tenths: 1 },
        { keys: ['священный символ', 'кошель с компонентами'], tenths: 1 },
        { keys: ['кандалы', 'manacles'], tenths: 1 },
        { keys: ['башенный щит', 'tower shield'], tenths: 40 },
        { keys: ['баклер', 'buckler'], tenths: 1 },
        { keys: ['щит', 'shield'], tenths: 10 }, // Стальной, деревянный, прочные и магические щиты = 1 Масса
        { keys: ['пояс силача', 'lifting belt'], tenths: 1 },
        { keys: ['руна', 'rune'], tenths: 0 }, // Нанесённые руны не имеют отдельного веса
        { keys: ['ингредиент', 'ingredient'], tenths: 0 }
    ];

    const parseBulkTenths = (rawText) => {
        const s = String(rawText || '').toLowerCase();
        const mHeavy = s.match(/масс[аы]\s*[:\-]?\s*(\d+)/i);
        if (mHeavy && mHeavy[1]) return (parseInt(mHeavy[1], 10) || 0) * 10;
        if (/(?:^|[\s(,])(?:масс[аы]\s*)?л(?:[\s).,]|$)/i.test(s)) return 1;
        return null;
    };

    // 2. Подсчёт всех 15 слотов рюкзака
    for (let i = 1; i <= 15; i++) {
        const name = String(stats?.[`item${i}Name`] || '').trim();
        const qty = Math.max(0, Number(stats?.[`item${i}Qty`]) || 0);
        const notes = String(stats?.[`item${i}Notes`] || '').trim();
        if ((!name && !notes) || qty === 0) continue;

        const cleanName = name.replace(/^[^\p{L}\p{N}]+/u, '').trim().toLowerCase().replace(/ё/g, 'е');
        if (cleanName.includes('пояс силача') || cleanName.includes('lifting belt')) {
            extraLimit = Math.max(extraLimit, 1);
        }

        const found = PF2E_ITEMS_CATALOG.find(it => {
            const target = it.name.replace(/^[^\p{L}\p{N}]+/u, '').trim().toLowerCase().replace(/ё/g, 'е');
            return target === cleanName || (cleanName.length > 3 && target.includes(cleanName));
        });

        const heroLvl = Math.max(1, Number(stats?.level) || 1);
        const itemLvl = found ? getItemLevel(found) : 0;
        if (found?.bulkBonus && itemLvl <= heroLvl) {
            extraLimit += Number(found.bulkBonus) || 0;
        }

        let unitTenths = null;
        if (found?.bulk !== undefined) {
            unitTenths = found.bulk === 'Л' ? 1 : (Number(found.bulk) || 0) * 10;
        } else {
            unitTenths = parseBulkTenths(notes) ?? (found ? parseBulkTenths(found.notes) : null);
        }

        if (unitTenths === null) {
            const matchedKnown = knownBulkTenths.find(entry => entry.keys.some(k => cleanName.includes(k)));
            if (matchedKnown) unitTenths = matchedKnown.tenths;
        }

        if (unitTenths === null && found) {
            if (/^(Зелье|Эликсир|Бомба|Свиток|Талисман|Масло|Посох|Жезл|Носимый)/i.test(found.category)) {
                unitTenths = 1;
            } else if (/Инструменты/i.test(found.category)) {
                unitTenths = 10;
            }
        }

        if (unitTenths) {
            const itemTotalTenths = unitTenths * qty;
            heavyBulk += Math.floor(itemTotalTenths / 10);
            lightCount += itemTotalTenths % 10;
        }
    }

    const backpackTenths = heavyBulk * 10 + lightCount;
    let armorTenths = 0;
    let weaponsTenths = 0;

    // 3. Точный учёт надетого доспеха с 1-й страницы (по правилам PF2e)
    const armorType = String(stats?.armorType || 'unarmored');
    const armorName = String(stats?.armorName || '').toLowerCase().replace(/ё/g, 'е');
    if (armorType === 'unarmored') {
        if (armorName && !armorName.includes('без брони') && (armorName.includes('одежда') || armorName.includes('роба') || armorName.includes('ги'))) {
            armorTenths = 1; // 1 Л
        }
    } else if (armorType === 'light') {
        armorTenths = /(стеган|стёган|шелк|шёлк|лиственн)/i.test(armorName) ? 1 : 10; // Стёганка/Шёлк = Л, остальная лёгкая = 1
    } else if (armorType === 'medium') {
        armorTenths = 20; // Вся средняя броня = 2 Массы
    } else if (armorType === 'heavy') {
        armorTenths = /(полные латы|крепостные латы|латы бастиона|рыцарей преисподней|серых дев|о-ерой|горный)/i.test(armorName) ? 40 : 30; // Тяжёлые латы = 4, полулаты/пластинчатый = 3
    }
    heavyBulk += Math.floor(armorTenths / 10);
    lightCount += armorTenths % 10;

    // 4. Точный учёт оружия с 1-й страницы (лёгкое = 1 Л, одноручное = 1, двуручное/луки/арбалеты = 2)
    ['melee1Name', 'melee2Name', 'rangedName'].forEach(wKey => {
        const wName = String(stats?.[wKey] || '').trim().toLowerCase().replace(/ё/g, 'е');
        if (!wName) return;

        let wTenths = 10; // По умолчанию 1 Масса за одноручное оружие
        if (/кулак|безоруж|рукавиц|кастет/i.test(wName)) {
            wTenths = 0;
        } else if (/кинжал|нож|дага|серп|дротик|праща|сюрикен|стилет|духовая|трубка|вакидзаси|собакорез|топорик|легк|лёгк|кнут|умбон|шипы/i.test(wName)) {
            wTenths = 1; // 1 Л
        } else if (/двуруч|алебард|глефа|гвизарма|рунка|нагината|нодати|коса|палица|кувалда|фальшион|длинное копь|рыцарское копь|боевой посох|боевой цеп|метеоритный|кусаригама|шипастая цепь|изогнутый клинок|длинный лук|тяжелый арбалет|тяжёлый арбалет|аркебуза|мушкет|мушкетон|стреломет|стреломёт|праща-посох/i.test(wName)) {
            wTenths = 20; // 2 Массы
        }

        weaponsTenths += wTenths;
        heavyBulk += Math.floor(wTenths / 10);
        lightCount += wTenths % 10;
    });

    // 5. Учёт монет (1000 монет = 1 Масса)
    const totalCoins = (Number(stats?.coinsCopper) || 0) + (Number(stats?.coinsSilver) || 0) + (Number(stats?.coinsGold) || 0);
    const coinsTenths = Math.floor(totalCoins / 1000) * 10;
    heavyBulk += Math.floor(coinsTenths / 10);

    const encumberedLimit = Math.max(0, 5 + strMod + extraLimit);
    const maxLimit = Math.max(0, 10 + strMod + extraLimit);
    const totalBulk = heavyBulk + Math.floor(lightCount / 10);
    const remLight = lightCount % 10;

    const formatTenths = (t) => {
        const b = Math.floor(t / 10);
        const l = t % 10;
        if (b === 0 && l === 0) return '0';
        return b > 0 ? `${b}${l > 0 ? ` и ${l} Л` : ''}` : `${l} Л`;
    };

    return {
        totalBulk,
        remLight,
        encumberedLimit,
        maxLimit,
        extraLimit,
        isOverloaded: totalBulk > maxLimit,
        isEncumbered: totalBulk > encumberedLimit,
        breakdown: {
            armor: formatTenths(armorTenths),
            weapons: formatTenths(weaponsTenths),
            backpack: formatTenths(backpackTenths),
            coins: formatTenths(coinsTenths),
            totalCoins
        }
    };
}

/**
 * Извлекает уровень предмета из строки категории (например, "Носимый предмет (4 ур.)" -> 4)
 */
export function getItemLevel(item) {
    if (!item) return 0;
    if (typeof item.level === 'number') return item.level;
    const m = String(item.category || '').match(/\((\d+)\s*ур\.\)/i);
    return m && m[1] ? (parseInt(m[1], 10) || 0) : 0;
}
